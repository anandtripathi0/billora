import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('complete billing workflow with real authentication, PDFs, QR and manual sharing', async ({page, context, browser}, testInfo) => {
  test.setTimeout(600000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const suffix = `${Date.now()}-${Math.random().toString(36).slice(2,7)}`;
  const mobile = '9' + String(Math.floor(Math.random()*1e9)).padStart(9,'0');
  const password = 'E2E#SecurePass2026';
  await page.goto('/');
  await expect(page.locator('h1').first()).toBeVisible();
  await page.screenshot({path: testInfo.outputPath('homepage.png'), fullPage:true});
  await page.goto('/dashboard');
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel('Mobile Number').fill(mobile);
  await page.getByLabel('Password',{exact:true}).fill('InvalidPassword');
  await page.getByRole('button',{name:'Login'}).click();
  await expect(page.locator('.auth-form').getByRole('alert')).toContainText('Invalid mobile number or password');
  await page.getByRole('link',{name:'Create Account'}).click();

  await page.getByLabel('Store Name',{exact:true}).fill('E2E Cream Store');

  await page.getByLabel('Mobile Number').fill(mobile);
  await page.getByLabel('Password',{exact:true}).fill(password);

  await page.getByRole('button',{name:'Create Account'}).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await expect(page.getByRole('heading',{name:'Hii, E2E Cream Store! 👋'})).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading',{name:'Hii, E2E Cream Store! 👋'})).toBeVisible();
  expect((await context.cookies()).find(c=>c.name==='sessionid')?.httpOnly).toBe(true);
  expect(await page.evaluate(()=>getComputedStyle(document.documentElement).getPropertyValue('--bg').trim().toUpperCase())).toBe('#FAF7F0');
  await page.goto('/settings');
  await page.getByLabel('Business address').fill('12 Market Road, Pune');
  await page.getByLabel('GSTIN (optional)').fill('27ABCDE1234F1Z5');
  await page.getByLabel('UPI ID',{exact:true}).fill('test-not-a-real-payee@upi');
  await page.getByLabel('UPI payee name').fill('E2E Cream Store');
  await page.getByRole('button',{name:'Save business settings'}).click();
  await expect(page.getByRole('status')).toContainText('Business settings saved.');
  await page.goto('/products');
  await page.getByRole('button',{name:'Add product',exact:true}).first().click();
  await page.getByLabel('Product name',{exact:true}).fill('E2E Notebook');
  await page.getByLabel('SKU',{exact:true}).fill(`NB-${suffix}`);
  await page.getByLabel('Selling price (₹)',{exact:true}).fill('100');
  await page.getByLabel('Purchase price').fill('50');
  await page.getByLabel('Stock quantity').fill('10');
  await page.getByLabel('GST rate').fill('18');
  await page.getByRole('button',{name:'Save product'}).click();
  await expect(page.getByText('E2E Notebook',{exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByText('E2E Notebook',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Edit E2E Notebook',exact:true}).click();
  await page.getByLabel('Description',{exact:true}).fill('Updated description');
  await page.getByRole('button',{name:'Save product'}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.goto('/invoices/new');
  await page.getByRole('button',{name:'Quick add customer'}).click();
  await page.getByLabel('Customer name',{exact:true}).fill('A Customer');
  await page.getByLabel('Mobile number',{exact:true}).fill('9876543211');
  await page.getByLabel('WhatsApp number').fill('9876543212');
  await page.getByLabel('Address',{exact:true}).fill('Pune');
  await page.getByRole('button',{name:'Save customer'}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByLabel('Add product',{exact:true}).selectOption({label:'E2E Notebook · ₹100.00 · 10 left'});
  await page.getByLabel('Quantity for E2E Notebook').fill('2');
  await page.getByLabel('Invoice discount').fill('10');
  await page.getByLabel('Payment status',{exact:true}).selectOption('partial');
  await page.getByLabel('Amount already paid').fill('24.20');
  await page.getByLabel('Include UPI QR').check();
  await page.getByRole('button',{name:'Preview invoice'}).click();
  await expect(page.getByRole('dialog')).toContainText('₹224.20');
  const saved = page.waitForResponse(r=>new URL(r.url()).pathname.replace(/\/$/,'')==='/api/invoices'&&r.request().method()==='POST'&&r.status()>=200&&r.status()<300);
  await page.getByRole('button',{name:'Generate invoice'}).click();
  expect((await (await saved).json()).pdf_ready).toBe(true);
  await expect(page).toHaveURL(/\/invoices\/[0-9a-f-]+$/);
  await expect(page.getByRole('heading',{name:'INV-000001'})).toBeVisible();
  const invoicePath = new URL(page.url()).pathname;
  const qr = await (await page.request.get(`/api${invoicePath}/qr/`)).json();
  expect(new URL(qr.uri).searchParams.get('am')).toBe('200.00');
  await expect(page.getByAltText('UPI QR to pay ₹200.00')).toBeVisible();
  const downloading = page.waitForEvent('download');
  await page.getByRole('link',{name:'Download PDF'}).click();
  const download=await downloading;
  const pdfPath=testInfo.outputPath('invoice.pdf');
  await download.saveAs(pdfPath);
  expect((await readFile(pdfPath)).subarray(0,5).toString()).toBe('%PDF-');
  await page.getByRole('button',{name:'Share on WhatsApp',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await expect(dialog).toContainText('you must confirm sending');
  const href=await dialog.getByRole('link',{name:'Open WhatsApp'}).getAttribute('href');
  const whatsapp=new URL(href!);
  expect(whatsapp.hostname).toBe('wa.me');
  expect(whatsapp.pathname).toBe('/919876543212');
  const message=whatsapp.searchParams.get('text')!;
  expect(message).toContain('E2E Cream Store');
  expect(message).toContain('₹224.20');
  expect(message).toContain('INV-000001');
  const sharedUrl=message.match(/https?:\/\/[^\s]+\/api\/shared\/[^\s]+/)![0];
  const publicContext=await browser.newContext();
  const publicPdf=await publicContext.request.get(sharedUrl);
  expect(publicPdf.status()).toBe(200);
  expect((await publicPdf.body()).subarray(0,5).toString()).toBe('%PDF-');
  const privateResponse=await publicContext.request.get(new URL(`/api${invoicePath}/`,page.url()).href);
  expect([401,403]).toContain(privateResponse.status());
  await dialog.getByRole('button',{name:'Copy Invoice Message',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Copied to clipboard');
  // Verify a user-initiated popup without contacting WhatsApp or sending anything.
  await context.route('https://wa.me/**', route=>route.fulfill({contentType:'text/html',body:'WhatsApp handoff test'}));
  const opening=page.waitForEvent('popup');
  await dialog.getByRole('link',{name:'Open WhatsApp'}).click();
  const popup=await opening;
  await expect(popup).toHaveURL(href!);
  await popup.close();
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Record payment',exact:true}).click();
  await page.getByRole('button',{name:'Confirm payment'}).click();
  await expect(page.getByText('Paid',{exact:true})).toBeVisible();
  await expect(page.getByAltText('UPI QR to pay ₹200.00')).toHaveCount(0);
  await page.getByRole('button',{name:'Revoke sharing links'}).click();
  await page.getByRole('button',{name:'Revoke links',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  expect((await publicContext.request.get(sharedUrl)).status()).toBe(404);
  await publicContext.close();
  await page.goto('/customers');
  await page.getByRole('button',{name:'Edit A Customer'}).click();
  await page.getByLabel('Address',{exact:true}).fill('Updated customer address');
  await page.getByRole('button',{name:'Save customer'}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('link',{name:'View A Customer ledger'}).click();
  await expect(page.getByText('INV-000001',{exact:true})).toBeVisible();
  await page.goto('/products');
  await expect(page.getByRole('row').filter({hasText:'E2E Notebook'})).toContainText('8 pcs');
  await page.getByRole('button',{name:'Archive E2E Notebook',exact:true}).click();
  await page.getByRole('button',{name:'Archive product',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByLabel('Include archived').check();
  await expect(page.getByRole('row').filter({hasText:'E2E Notebook'})).toContainText('Inactive');
  await page.goto('/dashboard');
  await expect(page.getByRole('heading',{name:'Hii, E2E Cream Store! 👋'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
  await expect(page.locator('.recharts-surface').first()).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('dashboard.png'),fullPage:true});
  if(testInfo.project.name==='mobile') await page.getByRole('button',{name:'Open menu'}).click();
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel('Mobile Number').fill(mobile);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Login'}).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await expect(page.getByRole('heading',{name:'Hii, E2E Cream Store! 👋'})).toBeVisible();
  expect(errors).toEqual([]);
});

